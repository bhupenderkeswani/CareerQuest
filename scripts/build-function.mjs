// Bundles web/functions/role-chat.js (and the shared engine it imports) into ONE file that can be
// pasted into the Supabase dashboard or deployed with the CLI:
//   npm run build:fn   ->   ../supabase/functions/role-chat/index.ts
import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = resolve(root, '../supabase/functions/role-chat/index.ts');
mkdirSync(dirname(outFile), { recursive: true });

const result = await build({
  entryPoints: [resolve(root, 'functions/role-chat.js')],
  bundle: true, write: false, format: 'esm', platform: 'neutral', target: 'es2022', minify: false, legalComments: 'none', logLevel: 'error',
});
const banner = `// @ts-nocheck
// GENERATED by web/scripts/build-function.mjs (npm run build:fn) from web/functions/role-chat.js and
// web/src/lib/match.js. Do not edit by hand: change the sources and rebuild.
//
// Secrets this function reads (Edge Functions > Secrets). Set at least one model key:
//   GROQ_API_KEY, OPENROUTER_API_KEY, or LLM_BASE_URL + LLM_API_KEY + LLM_MODEL (for example a LiteLLM proxy)
// Optional: GROQ_MODEL, OPENROUTER_MODEL, CHAT_DEVICE_DAILY_CAP (30), CHAT_GLOBAL_DAILY_CAP (400), ALLOWED_ORIGIN.
// SUPABASE_URL, SUPABASE_ANON_KEY and SUPABASE_SERVICE_ROLE_KEY are provided by Supabase automatically.
`;
const code = banner + result.outputFiles[0].text;
writeFileSync(outFile, code);
console.log(`wrote ${outFile} (${(code.length / 1024).toFixed(1)} KB)`);
if (/from ['"]\.\.?\//.test(code)) throw new Error('bundle still has relative imports');

